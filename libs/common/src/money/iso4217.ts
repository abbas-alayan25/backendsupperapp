export type CurrencyCode =
  | (typeof ZERO_DECIMAL)[number]
  | (typeof TWO_DECIMAL)[number]
  | (typeof THREE_DECIMAL)[number]
  | (typeof FOUR_DECIMAL)[number];

const EXPONENTS: ReadonlyMap<string, number> = new Map<string, number>([
  ...ZERO_DECIMAL.map((code) => [code, 0] as const),
  ...TWO_DECIMAL.map((code) => [code, 2] as const),
  ...THREE_DECIMAL.map((code) => [code, 3] as const),
  ...FOUR_DECIMAL.map((code) => [code, 4] as const),
]);

export function isCurrencyCode(value: string): value is CurrencyCode {
  return EXPONENTS.has(value);
}

export function minorUnitExponent(currency: CurrencyCode): number {
  const exponent = EXPONENTS.get(currency);
  if (exponent === undefined) {
    throw new RangeError(`Unknown currency ${currency}`);
  }
  return exponent;
}
